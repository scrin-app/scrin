function wordmarkSvg(textColor, dotColor, { size = 1 } = {}) {
  const pad = 0;
  const w = wm.width + pad * 2;
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${-pad} ${wm.top - pad} ${w} ${wm.height + pad * 2}" width="${w * 10 * size}" height="${(wm.height + pad * 2) * 10 * size}" role="img" aria-label="scrin">` +
    `<g fill="none" stroke="${textColor}" stroke-width="${wm.stroke}" stroke-linejoin="round">${wm.paths.map((d) => `<path d="${d}"/>`).join('')}</g>` +
    `<rect x="${wm.dot.x}" y="${wm.dot.y}" width="${wm.dot.w}" height="${wm.dot.h}" rx="${wm.dot.rx}" fill="${dotColor}"/></svg>`
  );
}
