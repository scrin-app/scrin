const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const written = [];
function write(rel, content) {
  const p = join(ROOT, rel);
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, content.endsWith('\n') ? content : content + '\n', 'utf8');
  written.push(rel);
}
