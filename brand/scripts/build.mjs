// ---------------------------------------------------------------- 4. SVG masters
const VARIANTS = {
  master: { grid: 24, ...halves({ stroke: 2.75 }), scale: 0.8 }, // >= 64 px
  small: { grid: 24, ...halves({ stroke: 3 }), scale: 0.86 }, // 24-48 px
  micro: { grid: 16, ...microHalves(), scale: 1 }, // 16-20 px, pixel grid
};
const MONO_GAP = { master: 0.9, small: 1, micro: 1 };
function markGroup(v, colors, { gap = false, id = '', pathLength = false } = {}) {
  const src = gap
    ? v.grid === 16 ? microHalves({ gap: MONO_GAP.micro }) : halves({ stroke: v.stroke, gap: MONO_GAP.master })
    : v;
  const c = v.grid / 2;
  const pl = pathLength ? ' pathLength="1"' : '';
  const t = v.scale === 1 ? '' : ` transform="translate(${c} ${c}) scale(${v.scale}) translate(${-c} ${-c})"`;
  return (
    `<g${t}><g${id ? ` id="${id}"` : ''} class="scrin-mark" fill="none" stroke-width="${v.stroke}" stroke-linejoin="round">` +
    `<path class="scrin-mark__ivory" d="${src.ivory}" stroke="${colors[0]}"${pl}/>` +
    `<path class="scrin-mark__lagoon" d="${src.lagoon}" stroke="${colors[1]}"${pl}/></g></g>`
  );
}
function tileSvg(variantName, { size = 512, bg = 'ink', markColors = [B.ivory.hex, B['lagoon-bright'].hex], full = false } = {}) {
  const v = VARIANTS[variantName];
  const g = v.grid;
  const inset = full ? 0 : g / 24;
  const rx = full ? 0 : g * (5.25 / 24);
  const tile =
    bg === 'ink'
      ? `<defs><linearGradient id="t" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="${B['ink-hi'].hex}"/><stop offset="0.7" stop-color="${B.ink.hex}"/></linearGradient></defs>` +
        `<rect x="${inset}" y="${inset}" width="${g - 2 * inset}" height="${g - 2 * inset}" rx="${rx}" fill="url(#t)"/>` +
          (full ? '' : `<rect class="rim" x="${inset + 0.1}" y="${inset + 0.1}" width="${g - 2 * inset - 0.2}" height="${g - 2 * inset - 0.2}" rx="${rx - 0.1}" fill="none" stroke="${B['ink-rim'].hex}" stroke-width="0.2" stroke-opacity="0.9"/>`)
      : `<rect x="${inset}" y="${inset}" width="${g - 2 * inset}" height="${g - 2 * inset}" rx="${rx}" fill="${bg}"/>`;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${g} ${g}" width="${size}" height="${size}" role="img" aria-label="scrin">${tile}${markGroup(v, markColors)}</svg>`;
}
function symbolSvg(variantName, colors, { gap = false, size = 512 } = {}) {
  const v = VARIANTS[variantName];
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${v.grid} ${v.grid}" width="${size}" height="${size}" role="img" aria-label="scrin">${markGroup(v, colors, { gap })}</svg>`;
}
