// ---------------------------------------------------------------- 1. tokens (DTCG 2025.10)
const dtcgColor = (c, desc) => ({
  $value: { colorSpace: 'oklch', components: [c.l, c.c, c.h], hex: c.hex },
  ...(desc ? { $description: desc } : {}),
});
const STEP_JOBS = [
  'app background', 'subtle background', 'component bg', 'component bg hover', 'component bg active',
  'subtle border', 'interactive border', 'strong border / focus ring', 'solid', 'solid hover',
  'low-contrast text', 'high-contrast text',
];
const primitives = {
  $description:
    'Layer 1 - raw ramps, generated by brand/scripts/build.mjs from palette.mjs. Components never read these; semantic tokens reference them.',
  color: { $type: 'color' },
};
for (const [name, ramp] of Object.entries(ramps)) {
  primitives.color[name] = Object.fromEntries(ramp.map((c, i) => [String(i + 1), dtcgColor(c, STEP_JOBS[i])]));
}
primitives.color.brand = Object.fromEntries(Object.entries(B).map(([k, c]) => [k, dtcgColor(c)]));
for (const theme of ['light', 'dark']) {
  for (const [k, v] of Object.entries(status[theme])) {
    primitives.color[`${k}${theme === 'dark' ? '-dark' : ''}`] = {
      3: dtcgColor(v.bg), 9: dtcgColor(v.solid), 11: dtcgColor(v.fg),
    };
  }
}
write('tokens/primitives.tokens.json', JSON.stringify(primitives, null, 2));

const semanticTokens = {
  $description: 'Layer 2 - semantic slots per theme. Themes remap only this layer.',
};
for (const theme of ['light', 'dark']) {
  const t = { $type: 'color' };
  for (const [slot, v] of Object.entries(semantic[theme])) {
    const [group, key] = slot.split('.');
    t[group] ??= {};
    t[group][key] = Array.isArray(v)
      ? { $value: `{color.${v[0]}.${v[1]}}` }
      : dtcgColor(v);
  }
  t.status = {};
  for (const k of Object.keys(status[theme])) {
    const p = `color.${k}${theme === 'dark' ? '-dark' : ''}`;
    t.status[k] = { bg: { $value: `{${p}.3}` }, solid: { $value: `{${p}.9}` }, fg: { $value: `{${p}.11}` } };
  }
  semanticTokens[theme] = t;
}
semanticTokens['dark-amoled'] = {
  $type: 'color',
  $description: 'AMOLED surface mode: only bg.canvas changes; everything else inherits dark.',
  bg: { canvas: dtcgColor(amoledBg) },
};
write('tokens/semantic.tokens.json', JSON.stringify(semanticTokens, null, 2));

// ---------------------------------------------------------------- 2. packages/ui proposal check
// Exact replica of packages/ui/src/theme/tokens.ts derivePalette for the proposed default preset.
function derivePalette(mode, surface, h, c) {
  const tint = Math.min(c, 0.2) * 0.08;
  if (mode === 'light') {
    const accentL = h > 70 && h < 160 ? 0.47 : 0.52;
    return {
      bg: [0.985, tint * 0.5, h], surface: [1, 0, h], 'surface-2': [0.955, tint, h], fg: [0.2, tint, h],
      muted: [0.47, tint, h], outline: [0.86, tint, h], accent: [accentL, Math.min(c, 0.2), h],
      'accent-fg': [0.99, 0, h], success: [0.5, 0.13, 150], warning: [0.55, 0.14, 70], danger: [0.53, 0.19, 27],
    };
  }
  const am = surface === 'amoled';
  return {
    bg: am ? [0, 0, h] : [0.17, tint, h], surface: am ? [0.13, tint, h] : [0.215, tint, h],
    'surface-2': am ? [0.18, tint, h] : [0.26, tint, h], fg: [0.96, tint * 0.5, h], muted: [0.74, tint, h],
    outline: am ? [0.3, tint, h] : [0.36, tint, h], accent: [0.76, Math.min(c, 0.17), h],
    'accent-fg': [0.18, tint, h], success: [0.77, 0.15, 150], warning: [0.82, 0.14, 80], danger: [0.72, 0.17, 25],
  };
}

