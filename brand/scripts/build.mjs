function lockupSvg(colors, textColor, dotColor) {
  // symbol (24 grid, 16-unit-tall s spanning y 4..20) at scale k so the s = 1.45 x wordmark x-height.
  const k = 1.0;
  const v = VARIANTS.small;
  const sym = halves({ stroke: 3 });
  const gap = 7;
  const symW = 12 * k;
  const wmScale = (16 * k) / 16 / 1.3; // wordmark x-height = s height / 1.3
  const wmX = symW + gap;
  const wmY = 4 + (16 - 16 * wmScale) / 1 - 0; // baseline-align: wordmark baseline = s bottom (y 20)
  const width = wmX + wm.width * wmScale + 2;
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="5 2 ${width} 19" width="${width * 16}" height="${19 * 16}" role="img" aria-label="scrin">` +
    `<g fill="none" stroke-width="${v.stroke}" stroke-linejoin="round"><path d="${sym.ivory}" stroke="${colors[0]}"/><path d="${sym.lagoon}" stroke="${colors[1]}"/></g>` +
    `<g transform="translate(${6 + wmX} ${wmY}) scale(${wmScale})"><g fill="none" stroke="${textColor}" stroke-width="${wm.stroke}" stroke-linejoin="round">${wm.paths.map((d) => `<path d="${d}"/>`).join('')}</g>` +
    `<rect x="${wm.dot.x}" y="${wm.dot.y}" width="${wm.dot.w}" height="${wm.dot.h}" rx="${wm.dot.rx}" fill="${dotColor}"/></g></svg>`
  );
}
write('logo/lockup-horizontal-on-dark.svg', lockupSvg(DARK, B.ivory.hex, B['lagoon-bright'].hex));
